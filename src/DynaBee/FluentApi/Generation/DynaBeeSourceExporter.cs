namespace DynaBee.FluentApi.Generation
{
    using System.Text;

    /// <summary>
    /// Exports the declarative shape of a DynaBee generation plan as deterministic C# source.
    /// Method bodies are represented by explicit placeholders because arbitrary runtime delegates cannot be translated safely to C#.
    /// </summary>
    public sealed class DynaBeeSourceExporter
    {
        /// <summary>
        /// Exports a generation plan to C# source and declaration mappings.
        /// </summary>
        /// <param name="plan">Plan to export.</param>
        /// <returns>Source and source-map entries.</returns>
        public DynaBeeSourceExportResult Export(DynaBeeGenerationPlan plan)
        {
            if (plan == null)
                throw new ArgumentNullException(nameof(plan));

            var source = new StringBuilder();
            var mappings = new List<DynaBeeSourceMapEntry>();
            source.AppendLine("// <auto-generated />");
            source.AppendLine($"// DynaBee plan fingerprint: {plan.GetFingerprint()}");
            source.AppendLine("#nullable enable");
            source.AppendLine();

            foreach (var classPlan in plan.Classes.OrderBy(x => x.Name, StringComparer.Ordinal))
                WriteClass(source, mappings, classPlan);

            return new DynaBeeSourceExportResult(source.ToString(), mappings);
        }

        private static void WriteClass(StringBuilder source, ICollection<DynaBeeSourceMapEntry> mappings, DynaBeeGeneratedClassPlan classPlan)
        {
            SplitTypeName(classPlan.Name, out var namespaceName, out var typeName);
            if (!string.IsNullOrWhiteSpace(namespaceName))
            {
                source.Append("namespace ").Append(namespaceName).AppendLine(";");
                source.AppendLine();
            }

            var inheritance = new[] { classPlan.BaseType }
                .Concat(classPlan.Interfaces)
                .Where(x => x != null && x != typeof(object))
                .Select(FormatType)
                .ToArray();
            mappings.Add(new DynaBeeSourceMapEntry(classPlan.Name, null, GetLine(source)));
            source.Append("public partial class ").Append(typeName);
            if (inheritance.Length != 0)
                source.Append(" : ").Append(string.Join(", ", inheritance));
            source.AppendLine();
            source.AppendLine("{");

            foreach (var member in classPlan.Members.OrderBy(x => x.ElementType).ThenBy(x => x.Name, StringComparer.Ordinal))
                WriteMember(source, mappings, classPlan.Name, member);

            source.AppendLine("}");
            source.AppendLine();
        }

        private static void WriteMember(
            StringBuilder source,
            ICollection<DynaBeeSourceMapEntry> mappings,
            string typeName,
            DynaBeeGeneratedMemberPlan member)
        {
            mappings.Add(new DynaBeeSourceMapEntry(typeName, member.Name, GetLine(source)));
            switch (member.ElementType)
            {
                case ElementType.Field:
                    source.Append("    private ").Append(FormatType(member.ValueType)).Append(' ').Append(member.Name).AppendLine(";");
                    break;
                case ElementType.Property:
                    source.Append("    public ").Append(FormatType(member.ValueType)).Append(' ').Append(member.Name).AppendLine(" { get; set; }");
                    break;
                case ElementType.Method:
                    if (member.Name == ".ctor")
                    {
                        source.AppendLine("    // Constructor body is emitted at runtime.");
                        break;
                    }

                    var parameters = member.ParameterTypes
                        .Select((type, index) => $"{FormatType(type)} arg{index}");
                    source.Append("    public ").Append(FormatType(member.ValueType)).Append(' ').Append(member.Name)
                        .Append('(').Append(string.Join(", ", parameters)).AppendLine(")");
                    source.AppendLine("        => throw new global::System.NotSupportedException(\"This method body is emitted by DynaBee at runtime.\");");
                    break;
                default:
                    source.Append("    // Unsupported planned element: ").Append(member.Name).AppendLine();
                    break;
            }
        }

        private static void SplitTypeName(string fullName, out string namespaceName, out string typeName)
        {
            var separator = fullName.LastIndexOf('.');
            namespaceName = separator < 0 ? null : fullName[..separator];
            typeName = separator < 0 ? fullName : fullName[(separator + 1)..];
        }

        private static string FormatType(Type type)
        {
            if (type == null)
                return "void";

            if (type == typeof(void)) return "void";
            if (type == typeof(string)) return "string";
            if (type == typeof(object)) return "object";
            if (type == typeof(bool)) return "bool";
            if (type == typeof(int)) return "int";
            if (type == typeof(decimal)) return "decimal";
            if (type.IsArray) return $"{FormatType(type.GetElementType()!)}[]";
            if (type.IsGenericType)
            {
                var name = type.GetGenericTypeDefinition().FullName!;
                name = name[..name.IndexOf('`')].Replace('+', '.');
                return $"global::{name}<{string.Join(", ", type.GetGenericArguments().Select(FormatType))}>";
            }

            return $"global::{(type.FullName ?? type.Name).Replace('+', '.')}";
        }

        private static int GetLine(StringBuilder source)
            => source.ToString().Count(x => x == '\n') + 1;
    }
}
